"""Auditable extraction and as-of joins of issuer-vintage fundamentals.

No latest-value historical backfill. Each source stays a separate vintage.
Unknown SEC acceptance/amendment timestamps are left null, never fabricated.
"""
import json,re,subprocess
from pathlib import Path
import numpy as np
import pandas as pd
from recover_e6_fundamentals import OUT,ROOT,sha,dump

CORE=['revenue_yoy','eps_yoy_symmetric','gross_margin','net_margin','operating_margin','cfo_margin','cash_asset_ratio']
DATEPAT=r'(?:January|February|March|April|May|June|July|August|September|October|November|December)\s+\d{1,2},?\s+20\d{2}'
NUM=r'\(?-?\d[\d,]*(?:\.\d+)?\)?%?'

def values(text):
    a=[]
    text=text.replace('−','-').replace('–','-')
    text=re.sub(r'\(\s*([\d,.]+)\s*\)',r'(\1)',text)
    for t in re.findall(NUM,text):
        v=float(t.replace(',','').replace('%','').replace('(','-').replace(')',''))
        a.append(v)
    return a

def table_row(text,patterns):
    for pattern in patterns:
        ls=text.splitlines()
        for i,line in enumerate(ls):
            m=re.match(r'^\s*'+pattern+r'\s*[.\s:$]*(.*)$',line,re.I)
            if m:
                tail=re.sub(r'^(?:\s*\(\d(?:\s*,\s*\d)*\))+\s*','',m.group(1))
                if re.match(r'[A-Za-z]',tail.strip().lstrip('$').strip()):continue
                vals=values(tail)
                if not vals:
                    for following in ls[i+1:i+4]:
                        if not following.strip():continue
                        if re.fullmatch(r'[\s$(),.\d%+\-]+',following):
                            cleaned=re.sub(r'^(?:\s*\(\d(?:\s*,\s*\d)*\))+\s*','',following)
                            vals=values(cleaned);line=line+' / '+following
                        break
                if vals:return vals,line.strip()
    return [],None

def ratio(a,b):return float(a/b) if np.isfinite(a) and np.isfinite(b) and abs(b)>1e-12 else np.nan

def apple_extract(row,out):
    prose=(out/row.release_path).with_suffix('.txt').read_text()
    doc=out/row.document_path if isinstance(row.document_path,str) else None
    text=doc.with_suffix('.txt').read_text() if doc else ''
    full='STATEMENTS OF OPERATIONS' in text[:1500].upper() or 'STATEMENT OF OPERATIONS' in text[:1500].upper()
    evidence=[];v={};lines={}
    pats={'revenue':[r'Total net sales',r'Net sales'], 'net_income':[r'Net income'],
          'gross_profit':[r'Gross margin',r'Gross profit'],'operating_income':[r'Operating income'],
          'eps':[r'Diluted'],'assets':[r'Total assets'],
          'cash':[r'Cash and cash equivalents'],'cfo':[r'Cash generated by operating activities',r'Net cash (?:provided by|generated by) operating activities']}
    if full:
        for k,ps in pats.items():v[k],lines[k]=table_row(text,ps)
        # Footnote markers after labels are NOT observations.
        rev=v['revenue'];ni=v['net_income'];eps=v['eps']
        current=lambda k:v[k][0] if len(v[k]) else np.nan
        revnow=current('revenue');revprev=rev[1] if len(rev)>1 else np.nan
        nnow=current('net_income');enow=current('eps');eprev=eps[1] if len(eps)>1 else np.nan
        # Apple CF is fiscal YTD. Use same-vintage YTD revenue, NOT quarterly revenue.
        ytd_rev=rev[2] if len(rev)>=4 else revnow
        core={'revenue_yoy':ratio(revnow,revprev)-1,'eps_yoy_symmetric':ratio(enow-eprev,abs(enow)+abs(eprev)+.1),
              'gross_margin':ratio(current('gross_profit'),revnow),'net_margin':ratio(nnow,revnow),
              'operating_margin':ratio(current('operating_income'),revnow),'cfo_margin':ratio(current('cfo'),ytd_rev),
              'cash_asset_ratio':ratio(current('cash'),current('assets'))}
        for k,vals in v.items():
            if vals:evidence.append({'field':k,'values':json.dumps(vals),'evidence':lines[k],'source_path':str(doc.relative_to(out)),'basis':'current quarter first column; CF fiscal YTD; balance instant'})
    else:
        # Older releases link a product-sales data summary, not full statements.
        # Read only explicit current/prior amounts in their original prose.
        head=prose[:prose.find('Apple sold') if 'Apple sold' in prose else 3600]
        revs=[float(x) for x in re.findall(r'revenue of \$([\d.]+) billion',head,re.I)]
        nis=[float(x) for x in re.findall(r'net (?:quarterly )?(?:profit|income) of \$([\d.]+) billion',head,re.I)]
        epss=[float(x) for x in re.findall(r'(?:or )?\$([\d.]+) per diluted share',head,re.I)]
        gm=re.search(r'Gross margin was ([\d.]+) percent',prose,re.I)
        cfo=re.search(r'(?:generated|generating|generation of|generat[ei][a-z]*).*?\$([\d.]+) billion (?:in (?:operating )?cash flow from operations|in operating cash flow|in cash flow from operations|in cash generation)',prose,re.I)
        revnow=revs[0] if len(revs) else np.nan;revprev=revs[1] if len(revs)>1 else np.nan
        nnow=nis[0] if nis else np.nan;enow=epss[0] if epss else np.nan;eprev=epss[1] if len(epss)>1 else np.nan
        core={'revenue_yoy':ratio(revnow,revprev)-1,'eps_yoy_symmetric':ratio(enow-eprev,abs(enow)+abs(eprev)+.1),
              'gross_margin':float(gm.group(1))/100 if gm else np.nan,'net_margin':ratio(nnow,revnow),
              'operating_margin':np.nan,'cfo_margin':np.nan,'cash_asset_ratio':np.nan}
        # Prose CFO can be annual/YTD without explicit same-basis denominator:
        # retain the number as audit-only, never guess a quarter CFO feature.
        evidence.append({'field':'original_release_prose','values':json.dumps({'revenue_billion':revs,'net_income_billion':nis,'EPS':epss,'prose_CFO_audit_only':cfo.group(1) if cfo else None}),'evidence':head,'source_path':row.release_path,'basis':'rounded release prose; CFO not used'})
    m=re.search(r'quarter (?:which .*?and )?ended ('+DATEPAT+r')',prose[:3500],re.I)
    if not m:m=re.search(r'ended ('+DATEPAT+r')',prose[:3500],re.I)
    period=str(pd.Timestamp(m.group(1)).date()) if m else None
    return core,evidence,{'period_end':period,'extraction_basis':'issuer quarterly financial statements' if full else 'original issuer rounded earnings prose','revenue_current':revnow,'revenue_prior':revprev,'net_income_current':nnow,'EPS_current':enow,'EPS_prior':eprev,'unit':'USD millions' if full else 'USD billions except EPS','release_date':row.release_date}

def tesla_extract(row,out):
    doc=out/row.document_path;text=doc.with_suffix('.txt').read_text()
    if doc.with_suffix('.ocr.txt').exists():text+='\f'+doc.with_suffix('.ocr.txt').read_text()
    for old,new in [('incom e','income'),('Incom e','Income'),('Incom e','Income'),('com m on','common')]:text=text.replace(old,new)
    # Modern summary lists five quarters chronologically. Legacy income
    # statements list current quarter first. Select the actual labeled column.
    current_idx=0;mode='legacy current-quarter-first GAAP statements';summary=''
    for page in text.split('\f'):
        if 'FINANCIALSUMMARY' in re.sub(r'\s','',page).upper() and re.search(r'Total revenues',page,re.I):
            header=next((l for l in page.splitlines() if len(re.findall(r'Q[1-4]\s*[-\u2019\u0027]?\s*(?:20)?\d{2}',l))>=3),None)
            if header:
                qs=re.findall(r'Q([1-4])\s*[-\u2019\u0027]?\s*(20\d{2}|\d{2})',header)
                normalized=[(int(y) if len(y)==4 else 2000+int(y),int(q)) for q,y in qs]
                if (row.fiscal_year,row.quarter) in normalized:
                    current_idx=normalized.index((row.fiscal_year,row.quarter));mode='five-quarter issuer financial summary';summary=page;break
    income_pages=[p for p in text.split('\f') if 'CONSOLIDATEDSTATEMENTSOFOPERATIONS' in re.sub(r'\s','',p).upper()]
    source=summary or (income_pages[0] if income_pages else '')
    # PDF line wraps within GAAP loss-per-share labels are formatting only.
    source=re.sub(r'(per common share, basic and)\s*\n\s*',r'\1 ',source,flags=re.I)
    source=re.sub(r'(attributable to common)\s*\n\s*stockholders',r'\1 stockholders',source,flags=re.I)
    evidence=[];v={}
    pats={'revenue':[r'Total revenues',r'Total revenue'],
        'net_income':[r'Net (?:income(?: \(loss\))?|loss|\(loss\) income) attributable to common stockholders \(GAAP\)(?:\s*\(\d\))?',r'Net (?:income(?: \(loss\))?|loss|\(loss\) income) attributable to common stockholders(?:\s*\(\d\))?',r'Net (?:income|loss) attributable to common shareholders',r'Net (?:income(?: \(loss\))?|loss|\(loss\) income)'],
        'gross_profit':[r'Total gross profit',r'Gross profit'],
        'gross_margin':[r'Total GAAP gross margin',r'GAAP gross margin'],
        'operating_income':[r'Income from operations',r'Loss from operations',r'Income \(loss\) from operations',r'Loss \(income\) from operations',r'\(Loss\) income from operations'],
        'cfo':[r'Net cash provided by (?:\(used in\) )?operating activities',r'Net cash (?:used in|provided by) operating activities',r'Operating cash flow'],
        'eps':[r'EPS attributable to common stockholders, diluted \(GAAP\)(?:\s*\(\d\))?'],
        'cash':[r'Cash and cash equivalents(?: and restricted cash)?'], 'assets':[r'Total assets']}
    for k,ps in pats.items():
        v[k],line=table_row(source,ps)
        if v[k]:evidence.append({'field':k,'values':json.dumps(v[k]),'evidence':line,'source_path':row.document_path,'basis':mode,'column_index':current_idx})
    # Legacy diluted GAAP EPS appears below the income statement's EPS label,
    # not below non-GAAP reconciliation or weighted share counts.
    if not v['eps'] and not summary:
        m=re.search(r'(?:Net (?:loss|income) per (?:common )?share|(?:Basic and diluted )?(?:net )?(?:loss|income) per share|Earnings per share)',source,re.I)
        if m:
            neighborhood=source[m.start():]
            neighborhood=re.split(r'Shares used|Weighted.average shares|Notes:',neighborhood,flags=re.I)[0]
            val,line=table_row(neighborhood,[r'Net (?:loss|income) per (?:common )?share, basic and diluted',r'Basic and diluted',r'Diluted'])
            if val:v['eps']=val;evidence.append({'field':'eps','values':json.dumps(val),'evidence':line,'source_path':row.document_path,'basis':'legacy GAAP EPS neighborhood','column_index':0})
    def cur(k):return v[k][current_idx] if len(v[k])>current_idx else np.nan
    revenue=cur('revenue');net=cur('net_income');eps=cur('eps')
    # No latest-comparative backfill: YoY revenue is computed later from earlier
    # retained current-quarter vintages; EPS uses same-release comparative only.
    core={'revenue_yoy':np.nan,'eps_yoy_symmetric':np.nan,'gross_margin':cur('gross_margin')/100 if v['gross_margin'] else ratio(cur('gross_profit'),revenue),
          'net_margin':ratio(net,revenue),'operating_margin':ratio(cur('operating_income'),revenue),'cfo_margin':ratio(cur('cfo'),revenue) if summary else np.nan,'cash_asset_ratio':np.nan}
    if summary and current_idx>=4:
        prev=v['revenue'][current_idx-4];core['revenue_yoy']=ratio(revenue,prev)-1
        if len(v['eps'])>current_idx:
            ep=v['eps'][current_idx-4];core['eps_yoy_symmetric']=ratio(eps-ep,abs(eps)+abs(ep)+.1)
    balance=next((p for p in text.split('\f') if 'CONSOLIDATEDBALANCESHEET' in re.sub(r'\s','',p).upper()),'')
    ca,caline=table_row(balance,pats['cash']);assets,aline=table_row(balance,pats['assets'])
    if ca and assets:
        core['cash_asset_ratio']=ratio(ca[0],assets[0]);evidence.append({'field':'cash_asset_ratio','values':json.dumps([ca[0],assets[0]]),'evidence':caline+' / '+aline,'source_path':row.document_path,'basis':'current instant, same balance sheet'})
    # A full calendar date inside the original PDF is preferable to an IR
    # directory known to contain some day/month errors. Never use a date before
    # quarter end or borrow a subsequent report's numerical observations.
    end=pd.Period(f'{int(row.fiscal_year)}Q{int(row.quarter)}').end_time.normalize()
    dates=[]
    for m in re.finditer(DATEPAT,text[:18000]):
        try:d=pd.Timestamp(m.group(0))
        except ValueError:continue
        if end+pd.Timedelta(days=7)<=d<=end+pd.Timedelta(days=100):dates.append(str(d.date()))
    declared=pd.Timestamp(row.release_date);chosen=max([declared]+[pd.Timestamp(d) for d in dates[:2]])
    unit_scale=.001 if 'thousands' in source[:1000].lower() else 1.
    return core,evidence,{'period_end':str(end.date()),'release_date':str(chosen.date()),'document_dates_found':json.dumps(dates[:2]),'date_precision':'date_only; PDF crosscheck' if dates else 'date_only; issuer IR directory (retrieved via discovery copy)','extraction_basis':mode,'revenue_current':revenue*unit_scale,'EPS_current':eps,'net_income_current':net*unit_scale,'unit':'USD millions normalized; EPS as printed in that original vintage'}

def extract(out=OUT):
    inv=pd.read_csv(out/'tables/document_inventory.csv');rows=[];evidence=[]
    for r in inv.itertuples():
        core,ev,extra=(apple_extract if r.ticker=='AAPL' else tesla_extract)(r,out)
        ident=f'{r.ticker}_FY{int(r.fiscal_year)}_Q{int(r.quarter)}'
        ev=[{'vintage':ident,**e} for e in ev];evidence.extend(ev)
        rows.append({'vintage':ident,'ticker':r.ticker,'fiscal_year':int(r.fiscal_year),'quarter':int(r.quarter),**core,**extra,
            'release_url':getattr(r,'release_url',None),'document_url':getattr(r,'document_url',None),'document_path':r.document_path,
            'document_sha256':sha(out/r.document_path) if isinstance(r.document_path,str) else None,
            'filing_url':r.filing_url,'filing_path':getattr(r,'filing_path',None),'SEC_acceptance_datetime':None,'SEC_amendment_datetime':None,
            'historical_first_seen_verified':False,'historical_version_proven':False,'collection_origin':'E6 current retrieval of issuer-vintage documents, not contemporary capture'})
    z=pd.DataFrame(rows).sort_values(['ticker','release_date'])
    # Legacy Tesla GAAP amounts use USD thousands. Within-vintage ratios work;
    # use prior vintage revenue growth only where units/basis match, otherwise
    # leave unknown. Never splice a later split-adjusted EPS level backwards.
    for idx,r in z[z.ticker.eq('TSLA')].iterrows():
        old=z[(z.ticker=='TSLA')&(z.fiscal_year==r.fiscal_year-1)&(z.quarter==r.quarter)&(z.release_date<r.release_date)]
        if len(old) and pd.isna(r.revenue_yoy) and old.iloc[-1].extraction_basis==r.extraction_basis:
            z.at[idx,'revenue_yoy']=ratio(r.revenue_current,old.iloc[-1].revenue_current)-1
    # Keep unusual values in the audit; model transforms are bounded below.
    for c in CORE:z[c]=pd.to_numeric(z[c],errors='coerce')
    z.to_csv(out/'inputs/fundamental_vintages.csv',index=False)
    pd.DataFrame(evidence).to_csv(out/'audits/extraction_evidence.csv',index=False)
    coverage=z.groupby(['ticker','fiscal_year'])[CORE].agg(['count']).reset_index()
    coverage.columns=['_'.join(x).rstrip('_') if isinstance(x,tuple) else x for x in coverage.columns]
    coverage.to_csv(out/'tables/fundamental_coverage_by_year.csv',index=False)
    return z

def align(vintages,calendar,delay=2):
    """Date-only conservative next-session rule, no same-day or retro backfill."""
    calendar=pd.DatetimeIndex(calendar);v=vintages.sort_values('release_date').copy()
    locations=calendar.searchsorted(pd.to_datetime(v.release_date),side='right')+delay-1
    valid=locations<len(calendar);v=v.loc[valid].copy();locations=locations[valid]
    v['available_date']=calendar[locations];v['availability_policy']=f'{delay} sessions strictly after disclosed release DATE; intraday unavailable'
    right=v.sort_values('available_date').drop_duplicates('available_date',keep='last')
    left=pd.DataFrame({'date':calendar})
    a=pd.merge_asof(left,right,left_on='date',right_on='available_date',direction='backward')
    if (pd.to_datetime(a.release_date.dropna())>=a.loc[a.release_date.notna(),'date']).any():raise RuntimeError('Same-day/future filing leaked')
    a['release_age_days']=(a.date-pd.to_datetime(a.release_date)).dt.days
    for c in CORE:a.loc[a.release_age_days>370,c]=np.nan
    a.index=calendar
    return a

